def is_commentary_start(line):
    line = line.strip()
    return (
        line.startswith('شەيخ ') or
        line.startswith('ئەللامە ') or
        line.startswith('ئىمام ئىبنى ') or
        line.startswith('ئىمام نەۋەۋى') or
        line.startswith('فەقىھ ') or
        'شەرھلىرىدىن بەزىلىرى' in line or
        'شەرھىدىن بەزىلىرى' in line or
        'شەرھى:' in line or
        '«فەتھۇلبارى»دا' in line or
        'فەتھۇلبارىدا' in line or
        'بۇ ھەدىستىن ئالىدىغان پايدىلار' in line or
        'بۇ ھەدىستىن چىقىدىغان ھۆكۈملەر' in line
    )

