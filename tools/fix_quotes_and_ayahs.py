def normalize_quotes(ans: str) -> str:
    """
    Normalizes inverted and displaced Uyghur quotation marks in answer text.
    """
    # 1. Adjacent inverted quotes on words: word» «word -> «word word»
    ans = re.sub(r"([\u0600-\u06FF\uFB50-\uFDFF]+)»\s*«([\u0600-\u06FF\uFB50-\uFDFF]+)", r"«\1 \2»", ans)

    # 2. Inverted quotes around single words: word» « -> «word»
    ans = re.sub(r"([\u0600-\u06FF\uFB50-\uFDFF]+)»\s*«", r"«\1»", ans)

    # 3. Transposed opening quote after colon/intro: ": »" -> ": «"
    ans = re.sub(r"([:،])\s*»\s*", r"\1 «", ans)

    # 4. Multi-word transposed quotes: word» ... «word -> «word ... word»
    # Where middle does not contain any other quotes
    def repl_multi(m):
        w1 = m.group(1)
        mid = m.group(2).strip()
        fn1 = m.group(3) or ""
        w2 = m.group(4)
        fn2 = m.group(5) or ""

        content = f"{w1} {mid} {w2}" if mid else f"{w1} {w2}"
        suffix = ""
        if fn1 or fn2:
            fn = (fn1 + " " + fn2).strip(" ()")
            if fn:
                suffix = f"({fn})"
        return f"«{content}»{suffix}"

    pattern = re.compile(
        r"([\u0600-\u06FF\uFB50-\uFDFF]+)»"
        r"([^«»\n]*?)"
        r"(\([0-9]+\)|\))?\s*«\s*"
        r"([\u0600-\u06FF\uFB50-\uFDFF؟!\.]+)"
        r"(\s*\([0-9]+\)|\s*\()?"
    )

    prev = None
    while prev != ans:
        prev = ans
        ans = pattern.sub(repl_multi, ans)

    # 5. Simple »...« blocks where words are inside
    ans = re.sub(r"»\s*([^«»\n]+?)\s*«", r"«\1»", ans)

    # 6. Stray inverted single word: »word« -> «word»
    ans = re.sub(r"»\s*([\u0600-\u06FF\uFB50-\uFDFF]+)\s*«", r"«\1»", ans)

    # 7. Clean up flipped footnote/paren artifacts like: )«word ( -> word»
    ans = re.sub(r"\)«\s*([\u0600-\u06FF\uFB50-\uFDFF]+)\s*(?:\((?:\s*([0-9]+)\s*\))?|\()", r"\1»", ans)

    # 8. Clean up double closing/opening quotes like «« or »»
    ans = re.sub(r"«{2,}", "«", ans)
    ans = re.sub(r"»{2,}", "»", ans)

    # 9. Clean up reversed parentheses in footnote blocks: e.g. text. ) ( text2. ) (
    ans = re.sub(r"\)\s*\(\s*([^\n()]+?)\s*\)\s*\(", r"(\1)", ans)

    return ans


def process_all():
    mdx_files = sorted(DOCS_DIR.glob("**/*.mdx"))
    
    # Load JSON databases
    extracted_2000 = {}
    if JSON_EXTRACTED.exists():
        with open(JSON_EXTRACTED, "r", encoding="utf-8") as fp:
            extracted_2000 = json.load(fp)
            
    extracted_book2 = {}
    if JSON_BOOK2.exists():
        with open(JSON_BOOK2, "r", encoding="utf-8") as fp:
            extracted_book2 = json.load(fp)

    total_modified_cards = 0
    modified_files = set()

    for mdx_path in mdx_files:
        content = mdx_path.read_text(encoding="utf-8")
        orig_content = content

        # 1. Apply Arabic replacements globally across content
        for broken, fixed in ARABIC_REPLACEMENTS.items():
            if broken in content:
                content = content.replace(broken, fixed)

        # 2. Process QA cards
        card_re = re.compile(r'(<div class="qa-card" id="q(\d+)">.*?<div class="qa-answer">)(.*?)(</div>\s*</div>)', re.DOTALL)
        
        def replace_card(m):
            nonlocal total_modified_cards
            header = m.group(1)
            qnum = int(m.group(2))
            ans = m.group(3)
            footer = m.group(4)
            orig_ans = ans

            # Specific question override if defined
            if qnum in SPECIFIC_QUESTION_FIXES:
                ans = SPECIFIC_QUESTION_FIXES[qnum]
            else:
                # In Book 1 Part 2/3 (Q648-Q1317) and where quotes are inverted, normalize
                quotes = [c for c in ans if c in "«»"]
                if quotes and quotes[0] == "»":
                    ans = normalize_quotes(ans)
                elif "» «" in ans or ")«" in ans or "«(" in ans:
                    ans = normalize_quotes(ans)

            if ans != orig_ans:
                total_modified_cards += 1
                q_key = str(qnum)
                # Update JSON databases
                if q_key in extracted_2000:
                    extracted_2000[q_key]["answer"] = ans
                if q_key in extracted_book2:
                    extracted_book2[q_key]["answer"] = ans

            return f"{header}{ans}{footer}"

        content = card_re.sub(replace_card, content)

        if content != orig_content:
            mdx_path.write_text(content, encoding="utf-8")
            modified_files.add(mdx_path.name)

    # Save updated JSON databases
    with open(JSON_EXTRACTED, "w", encoding="utf-8") as fp:
        json.dump(extracted_2000, fp, ensure_ascii=False, indent=2)

    with open(JSON_BOOK2, "w", encoding="utf-8") as fp:
        json.dump(extracted_book2, fp, ensure_ascii=False, indent=2)

    print(f"Processed complete. Modified {total_modified_cards} cards across {len(modified_files)} MDX files.")


if __name__ == "__main__":
    process_all()
