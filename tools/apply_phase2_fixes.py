#!/usr/bin/env python3
# -*- coding: utf-8 -*-

import glob
import re
from pathlib import Path

DOCS_DIR = Path("src/content/docs/aile")
files = sorted(DOCS_DIR.glob("**/*.mdx"))

def fix_phase2(text):
    # 1. Join separated plural -لار / -لەر to preceding word
    # e.g., مۆمىن لەرنىڭ -> مۆمىنلەرنىڭ, ئېلىشىڭ لار -> ئېلىشىڭلار
    text = re.sub(r'([\u0621-\u06FF]+)\s+(لار|لەر)([\u0621-\u06FF]*)\b', r'\1\2\3', text)

    # 2. Fix modal auxiliary auxiliary roots: قىال... -> قىلال... / قىل...
    modal_qil = [
        (r'\bقىاللايدۇ\b', 'قىلالايدۇ'),
        (r'\bقىاللايدىغان\b', 'قىلالايدىغان'),
        (r'\bقىاللايمەن\b', 'قىلالايمەن'),
        (r'\bقىاللمايدۇ\b', 'قىلالمايدۇ'),
        (r'\bقىاللمايدىغان\b', 'قىلالمايدىغان'),
        (r'\bقىاللمايدىغانلىقى\b', 'قىلالمايدىغانلىقى'),
        (r'\bقىاللمايدىغانلىقىنى\b', 'قىلالمايدىغانلىقىنى'),
        (r'\bقىاللماي\b', 'قىلالماي'),
        (r'\bقىاللمايۋاتىمىز\b', 'قىلالمايۋاتىمىز'),
        (r'\bقىاللمىغان\b', 'قىلالمىغان'),
        (r'\bقىاللمىغانلار\b', 'قىلالمىغانلار'),
        (r'\bقىاللمىغانلىق\b', 'قىلالمىغانلىق'),
        (r'\bقىاللمىغانلىقى\b', 'قىلالمىغانلىقى'),
        (r'\bقىاللمىغانلىقىڭىز\b', 'قىلالمىغانلىقىڭىز'),
        (r'\bقىاللمىدى\b', 'قىلالمىدى'),
        (r'\bقىاللماسلىق\b', 'قىلالماسلىق'),
        (r'\bقىاللماسلىقىدىن\b', 'قىلالماسلىقىدىن'),
        (r'\bقىاللماستىن\b', 'قىلالماستىن'),
        (r'\bقىاللىسىمۇ\b', 'قىلالىسىمۇ'),
        (r'\bقىاللىغۇدەك\b', 'قىلالىغۇدەك'),
        (r'\bقىالتتى\b', 'قىلاتتى'),
        (r'\bقىالتتىم\b', 'قىلاتتىم'),
        (r'\bقىالتتۇق\b', 'قىلاتتۇق'),
        (r'\bقىال\b', 'قىلا'),
    ]
    for pat, rep in modal_qil:
        text = re.sub(pat, rep, text)

    # 3. Fix modal auxiliary roots: بۋال... -> بولال... / بول...
    modal_bol = [
        (r'\bبۋاللايدۇ\b', 'بولالايدۇ'),
        (r'\bبۋاللايدىغان\b', 'بولالايدىغان'),
        (r'\bبۋالالمدۇ\b', 'بولالامدۇ'),
        (r'\bبۋاللمايدۇ\b', 'بولالمايدۇ'),
        (r'\bبۋاللمايدىغان\b', 'بولالمايدىغان'),
        (r'\bبۋاللماي\b', 'بولالماي'),
        (r'\bبۋاللمايمەن\b', 'بولالمايمەن'),
        (r'\bبۋاللمايسىلەر\b', 'بولالمايسىلەر'),
        (r'\bبۋاللمىغان\b', 'بولالمىغان'),
        (r'\bبۋاللمىغانلىق\b', 'بولالمىغانلىق'),
        (r'\bبۋاللمىغانلىقى\b', 'بولالمىغانلىقى'),
        (r'\bبۋاللماسلىقى\b', 'بولالماسلىقى'),
        (r'\bبۋاللماسلىقىدىن\b', 'بولالماسلىقىدىن'),
        (r'\bبۋالتتى\b', 'بولاتتى'),
        (r'\bبۋالتتىم\b', 'بولاتتىم'),
        (r'\bبۋاللىغان\b', 'بولاللىغان'),
        (r'\bبۋالي\b', 'بولاي'),
        (r'\bبۋال\b', 'بولا'),
    ]
    for pat, rep in modal_bol:
        text = re.sub(pat, rep, text)

    # 4. Fix modal auxiliary roots: قاال... -> قالال... / قال...
    modal_qal = [
        (r'\bقااللايدۇ\b', 'قالالايدۇ'),
        (r'\bقااللايمىز\b', 'قالالايىمىز'),
        (r'\bقااللمىغانلىقى\b', 'قالالمىغانلىقى'),
        (r'\bقااللمىغان\b', 'قالالمىغان'),
        (r'\bقاالمدۇ\b', 'قالامدۇ'),
        (r'\bقااليمىقان\b', 'قالامىقان'),
        (r'\bقاال\b', 'قالا'),
    ]
    for pat, rep in modal_qal:
        text = re.sub(pat, rep, text)

    # 5. Compound forms with double-alif / inversions
    compounds = [
        (r'\bئېيتااليمىزكى\b', 'ئېيتالايمىزكى'),
        (r'\bئېيتااليمەنكى\b', 'ئېيتالايمەنكى'),
        (r'\bباھااليتتى\b', 'باھالايتتى'),
        (r'\bبىلىۋاالاليمىزكى\b', 'بىلىۋالالايمىزكى'),
        (r'\bبىلىۋااللايمىز\b', 'بىلىۋالالايمىز'),
        (r'\bبۇنچىۋاال\b', 'بۇنچىۋالا'),
        (r'\bبېسىۋاالالي\b', 'بېسىۋالالاي'),
        (r'\bتارتىۋااللمايدۇ\b', 'تارتىۋالالمايدۇ'),
        (r'\bقايتۇرىۋااللايدۇ\b', 'قايتۇرىۋالالايدۇ'),
        (r'\bقىلىۋاالمدىغاندۇ\b', 'قىلىۋالامدىغاندۇ'),
        (r'\bيارىشىۋااللايدۇ\b', 'يارىشىۋالالايدۇ'),
        (r'\bيۇتۇۋااللايدۇ\b', 'يۇتۇۋالالايدۇ'),
        (r'\bچىقىرااليتتى\b', 'چىقىرالايتتى'),
        (r'\bتاال\b', 'تالا'),
        (r'\bتاالغا\b', 'تالاغا'),
        (r'\bساال\b', 'سالا'),
        (r'\bكاال\b', 'كالا'),
        (r'\bھاال\b', 'ھالا'),
        (r'\bئۆلىماال\b', 'ئۆلىمالار'),
        (r'\bقاندۇرالمايد\b', 'قاندۇرالمايدۇ'),
        (r'\bتۇرۇپال\b', 'تۇرۇپلا'),
        (r'\bقۋيۇۋالىدۇ\b', 'قويۇۋالىدۇ'),
        (r'\bقۋراللىرىمۇ\b', 'قوراللىرىمۇ'),
        (r'\bقۋرقۇڭال\b', 'قورقۇڭلار'),
        (r'\bساقالڭلار\b', 'ساقلاڭلار'),
        (r'\bساقالڭ\b', 'ساقلاڭ'),
        (r'\bقىلىڭال\b', 'قىلىڭلار'),
        (r'\bئۋقۇڭال\b', 'ئوقۇڭلار'),
        (r'\bقانائەتال\b', 'قانائەتلا'),
    ]
    for pat, rep in compounds:
        text = re.sub(pat, rep, text)

    return text

total = 0
for f in files:
    content = f.read_text(encoding='utf-8')
    fixed = fix_phase2(content)
    if fixed != content:
        f.write_text(fixed, encoding='utf-8')
        total += 1
        print(f"Phase 2 applied to {f}")

print(f"Phase 2 complete! {total} files updated.")
