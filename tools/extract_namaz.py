def fix_rtl_line_punctuation(line: str) -> str:
    line = line.strip()
    if not line:
        return ""
    m = re.match(r'^([.,،!؟:؛\-\)\(»«\s]+)(.+)$', line)
    if m:
        punct = m.group(1).strip()
        rest = m.group(2).strip()
        if punct in ['.', '،', '!', '؟', ':', '؛']:
            return rest + punct
        if punct in ['..', '...', '---', '_', '-']:
            return rest
    return line

def detect_numbered_item(raw: str):
    raw = raw.strip()
    m = re.match(r'^([.,،:؛\-\)\(»«\s_–]+)?(.*?)\s*(\d+)[\.\)\-]*$', raw)
    if not m:
        return None
    punct = m.group(1) or ''
    body = m.group(2).strip()
    num = int(m.group(3))
    if num > 30:
        return None
    if re.match(r'^[\-–_.\s]*ئايەت[\-–_.\s]*$', body):
        return None
    if not punct and not ('_ .' in raw or '_. ' in raw or '_ ' in raw or raw.startswith(('{', '}', '﴾', '«'))):
        return None
    m_inv = re.match(r'^(.*?)\s*_\s*\.\s*(.+)$', body)
    if m_inv:
        prefix = m_inv.group(2).strip()
        rest = m_inv.group(1).strip()
        body = f'{prefix} — {rest}'
    if body.count('(') > body.count(')'):
        body += ')'
    return num, body

