def clean_text(t):
    s = ''.join([mapping.get(c, c) for c in t])
    for pattern, rep in WORD_REPLACEMENTS:
        s = re.sub(pattern, rep, s)
    s = s.replace('ـ', '')
    return s

def is_garbled_quran_font(txt):
    if '' in txt or '〈' in txt or '©!' in txt or 'tβθ' in txt or 'öΝ' in txt or 'ø9$' in txt or 'šχθ' in txt:
        return True
    if re.search(r'[a-zA-Z]{3,}', txt) and ('ö' in txt or 'ä' in txt or 'ß' in txt or 'ç' in txt or 'é' in txt or 'è' in txt or 'ø' in txt or 'ù' in txt or 'ú' in txt):
        return True
    return False

def escape_mdx(txt):
    # Escape JSX-sensitive characters
    txt = txt.replace('<', '&lt;').replace('>', '&gt;')
    txt = txt.replace('{', '&#123;').replace('}', '&#125;')
    return txt

