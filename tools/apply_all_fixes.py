def run():
    mdx_files = sorted(DOCS_DIR.glob("**/*.mdx"))
    
    with open(JSON_EXTRACTED, "r", encoding="utf-8") as fp:
        extracted_2000 = json.load(fp)
    with open(JSON_BOOK2, "r", encoding="utf-8") as fp:
        extracted_book2 = json.load(fp)

    files_modified = 0
    cards_modified = 0

    for mdx_path in mdx_files:
        content = mdx_path.read_text(encoding="utf-8")
        orig_content = content

        for broken, fixed in TARGET_REPLACEMENTS.items():
            if broken in content:
                content = content.replace(broken, fixed)

        # Update JSON databases for modified cards
        card_re = re.compile(r'(<div class="qa-card" id="q(\d+)">.*?<div class="qa-answer">)(.*?)(</div>\s*</div>)', re.DOTALL)
        for m in card_re.finditer(content):
            qnum_str = m.group(2)
            ans = m.group(3).strip()
            if qnum_str in extracted_2000:
                if extracted_2000[qnum_str]["answer"] != ans:
                    extracted_2000[qnum_str]["answer"] = ans
                    cards_modified += 1
            if qnum_str in extracted_book2:
                if extracted_book2[qnum_str]["answer"] != ans:
                    extracted_book2[qnum_str]["answer"] = ans

        if content != orig_content:
            mdx_path.write_text(content, encoding="utf-8")
            files_modified += 1

    with open(JSON_EXTRACTED, "w", encoding="utf-8") as fp:
        json.dump(extracted_2000, fp, ensure_ascii=False, indent=2)
    with open(JSON_BOOK2, "w", encoding="utf-8") as fp:
        json.dump(extracted_book2, fp, ensure_ascii=False, indent=2)

    print(f"Applied fixes across {files_modified} files, {cards_modified} cards updated in DB.")


if __name__ == "__main__":
    run()
