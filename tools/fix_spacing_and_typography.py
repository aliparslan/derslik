def clean_outside_tags(content: str) -> str:
    """Apply spacing regexes exclusively to text content outside HTML tags."""
    # Split content by HTML tags <...>
    parts = re.split(r"(<[^>]+>)", content)

    for idx in range(0, len(parts), 2):
        chunk = parts[idx]

        # 1. Number punctuation artifacts: e.g. 1892 -، يىلى -> 1892-يىلى
        chunk = re.sub(r"(\d+)\s*[-–—]\s*،\s*(" + UY_LETTER + r")", r"\1-\2", chunk)

        # 2. Number + Uyghur letter: e.g. 12يىل -> 12 يىل
        chunk = re.sub(r"(\d+)(" + UY_LETTER + r")", r"\1 \2", chunk)

        # 3. Uyghur letter + Number: e.g. سۈرىسى159 -> سۈرىسى 159, خەلىپىلىكى1892 -> خەلىپىلىكى 1892
        chunk = re.sub(r"(" + UY_LETTER + r")(\d+)", r"\1 \2", chunk)

        # 4. Comma followed by Uyghur letter: e.g. ،توم -> ، توم
        chunk = re.sub(r"،(" + UY_LETTER + r")", r"، \1", chunk)

        # 5. Colon followed by Uyghur letter: e.g. :ئەلەيھىسسالام -> : ئەلەيھىسسالام
        chunk = re.sub(r":(" + UY_LETTER + r")", r": \1", chunk)

        # 6. Footnote label followed by word: e.g. (1)ئىمام -> (1) ئىمام
        chunk = re.sub(r"(\(\d+\))(" + UY_LETTER + r"{2,})", r"\1 \2", chunk)

        # 7. Letter followed by open paren: e.g. بىرىدۇر( -> بىرىدۇر (
        chunk = re.sub(r"(" + UY_LETTER + r"{2,})(\()", r"\1 \2", chunk)

        # 8. Known fused word pairs
        for defective, fixed in FUSED_WORDS:
            chunk = chunk.replace(defective, fixed)

        parts[idx] = chunk

    return "".join(parts)

