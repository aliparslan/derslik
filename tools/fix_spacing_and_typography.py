def process_file(filepath: Path) -> bool:
    with open(filepath, "r", encoding="utf-8") as fp:
        original = fp.read()

    modified = fix_special_cards(original)
    modified = clean_outside_tags(modified)

    if modified != original:
        with open(filepath, "w", encoding="utf-8") as fp:
            fp.write(modified)
        return True
    return False

def sync_json_datasets():
    """Sync json datasets with fixed question titles and answers."""
    # Build dictionary of all 2000 questions from MDX files
    card_re = re.compile(
        r'<div class="qa-card" id="q(\d+)">.*?<span class="qa-text">(.*?)</span>.*?<div class="qa-answer">(.*?)</div>\s*</div>',
        re.DOTALL
    )
    mdx_questions = {}
    for f in DOCS_DIR.glob("**/*.mdx"):
        with open(f, "r", encoding="utf-8") as fp:
            c = fp.read()
        for num_str, q_text, ans_html in card_re.findall(c):
            num = int(num_str)
            clean_q = re.sub(r"<[^>]+>", "", q_text).strip()
            # remove leading 'جاۋاب:' label
            clean_a = re.sub(r'<span class="qa-label">.*?</span>', '', ans_html).strip()
            clean_a = re.sub(r"<[^>]+>", "", clean_a).strip()
            mdx_questions[num] = (clean_q, clean_a)

    print(f"Loaded {len(mdx_questions)} questions from MDX files")

    # Update extracted_2000_book2.json
    if B2_JSON.exists():
        with open(B2_JSON, "r", encoding="utf-8") as fp:
            b2_data = json.load(fp)
        for item in b2_data:
            num = item.get("number")
            if num in mdx_questions:
                item["question"] = mdx_questions[num][0]
                item["answer"] = mdx_questions[num][1]
        with open(B2_JSON, "w", encoding="utf-8") as fp:
            json.dump(b2_data, fp, ensure_ascii=False, indent=2)
        print(f"Updated {B2_JSON}")

    # Update extracted_2000.json
    if ALL_JSON.exists():
        with open(ALL_JSON, "r", encoding="utf-8") as fp:
            all_data = json.load(fp)
        for item in all_data:
            num = item.get("number")
            if num in mdx_questions:
                item["question"] = mdx_questions[num][0]
                item["answer"] = mdx_questions[num][1]
        with open(ALL_JSON, "w", encoding="utf-8") as fp:
            json.dump(all_data, fp, ensure_ascii=False, indent=2)
        print(f"Updated {ALL_JSON}")

def main():
    mdx_files = sorted(DOCS_DIR.glob("**/*.mdx"))
    changed = 0
    for f in mdx_files:
        if process_file(f):
            changed += 1
            print(f"Fixed: {f.relative_to(DOCS_DIR)}")

    print(f"\nTotal MDX files updated: {changed} / {len(mdx_files)}")

    print("\nSynchronizing JSON datasets...")
    sync_json_datasets()
    print("Done!")

if __name__ == "__main__":
    main()
