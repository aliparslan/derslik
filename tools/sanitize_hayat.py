#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
sanitize_hayat.py
Cleans up any remaining font artifacts, normalizes Uyghur spelling,
and ensures proper markdown formatting across all hayat docs.
"""

import re
from pathlib import Path

DOCS_DIR = Path("src/content/docs/hayat")

REPLACEMENTS = [
    (r'\ufeff', ''),
    (r'[\u200B-\u200D\u200E\u200F]', ''),
    (r'ò', ''),
    (r'Ĵ', ''),
    # Orthography refinements
    (r'\bئىشالر\b', 'ئىشلار'),
    (r'\bئىشالرنى\b', 'ئىشلارنى'),
    (r'\bئىشالرنىڭ\b', 'ئىشلارنىڭ'),
    (r'\bئىشالرغا\b', 'ئىشلارغا'),
    (r'\bئىشالردا\b', 'ئىشلاردا'),
    (r'\bئىشالردىن\b', 'ئىشلاردىن'),
    (r'\bئىشالرمۇ\b', 'ئىشلارمۇ'),
    (r'\bكۈنلـۈك\b', 'كۈنلۈك'),
    (r'\bكۈندىلىـك\b', 'كۈندىلىك'),
    (r'\bئاخىـر\b', 'ئاخىر'),
    (r'\bئاخىرقـى\b', 'ئاخىرقى'),
    (r'\bئاقىلالرچە\b', 'ئاقىلانىچە'),
    (r'\bئاقىالنىلىقتۇر\b', 'ئاقىلانىلىقتۇر'),
    (r'\bئاقىالنىلىـق\b', 'ئاقىلانىلىق'),
    (r'\bئاقىالنىلقتۇر\b', 'ئاقىلانىلىقتۇر'),
    (r'\bئاقىالنە\b', 'ئاقىلانە'),
    (r'\bباال\b', 'بالا'),
    (r'\bباالىرى\b', 'بالىلىرى'),
    (r'\bباال۔قازا\b', 'بالا-قازا'),
    (r'\bباال۔قازادىن\b', 'بالا-قازادىن'),
    (r'\bباال۔مۇسىبەت\b', 'بالا-مۇسىبەت'),
    (r'\bكۆپىنچىسـى\b', 'كۆپىنچىسى'),
    (r'\bكۆپىنچىسى\b', 'كۆپىنچىسى'),
    (r'\bقورقـۇڭالر\b', 'قورقۇڭلار'),
    (r'\bقورقۇڭالر\b', 'قورقۇڭلار'),
    (r'\bتەۋبـە\b', 'تەۋبە'),
    (r'\bتەۋبە\b', 'تەۋبە'),
    (r'\bئۈمىدسـىزلەنمەڭالر\b', 'ئۈمىدسىزلەنمەڭلار'),
    (r'\bئۈمىدسىزلەنمەڭالر\b', 'ئۈمىدسىزلەنمەڭلار'),
    (r'\bبولـۇڭالر\b', 'بولۇڭلار'),
    (r'\bبولۇڭالر\b', 'بولۇڭلار'),
    (r'\bقىلىـڭالر\b', 'قىلىڭلار'),
    (r'\bقىلىڭالر\b', 'قىلىڭلار'),
    (r'\bدېمـەڭالر\b', 'دېمەڭلار'),
    (r'\bدېمەڭالر\b', 'دېمەڭلار'),
    (r'\bقايتىـڭالر\b', 'قايتىڭلار'),
    (r'\bقايتىڭالر\b', 'قايتىڭلار'),
    (r'\bئېيتىـڭالر\b', 'ئېيتىڭلار'),
    (r'\bئېيتىڭالر\b', 'ئېيتىڭلار'),
    (r'\bسـوراڭالر\b', 'سوراڭلار'),
    (r'\bسوراڭالر\b', 'سوراڭلار'),
    (r'\bسېلىـڭالر\b', 'سېلىڭلار'),
    (r'\bسېلىڭالر\b', 'سېلىڭلار'),
    (r'\bتالالڭالر\b', 'تاللاڭلار'),
    (r'\bتـالالڭالر\b', 'تاللاڭلار'),
    (r'\bتالالڭ\b', 'تاللاڭ'),
    (r'\bتـالالڭ\b', 'تاللاڭ'),
    (r'\bپاراڭالش\b', 'پاراڭلىشىش'),
    (r'\bپاراڭالشـقاندا\b', 'پاراڭلاشقاندا'),
    (r'\bپاراڭالشقاندا\b', 'پاراڭلاشقاندا'),
    (r'\bتەكراراليغان\b', 'تەكرارلايدىغان'),
    (r'\bكۈلەلىگـەن\b', 'كۈلەلىگەن'),
    (r'\bكۈلەلىگەن\b', 'كۈلەلىگەن'),
    (r'\bھېچكىم تەنقىدلىمىسۇن دېسىڭىز\s*\.\.\.\b', 'ھېچكىم تەنقىدلىمىسۇن دېسىڭىز...'),
    (r'\bيېتەكلىگەن سـۆيۈملۈك پەيغەمبىرىمىز ھەزرىتى مۇھەممەد ئەلەيھىسسـا\s*-?\s*المغـا\b', 'يېتەكلىگەن سۆيۈملۈك پەيغەمبىرىمىز ھەزرىتى مۇھەممەد ئەلەيھىسسالامغا'),
]

for mdx_path in DOCS_DIR.rglob("*.mdx"):
    content = mdx_path.read_text(encoding="utf-8")
    for pat, rep in REPLACEMENTS:
        content = re.sub(pat, rep, content)
    # Clean broken ayah artifacts where Latin S or lone letters appear
    content = re.sub(r'\bS\b', '', content)
    content = re.sub(r' +', ' ', content)
    mdx_path.write_text(content, encoding="utf-8")
    print(f"Sanitized {mdx_path.name}")

print("Sanitization completed.")
